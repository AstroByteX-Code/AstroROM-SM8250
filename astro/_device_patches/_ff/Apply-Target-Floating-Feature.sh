# shellcheck disable=SC2094
APPLY_TARGET_FEATURE()
{
    local SOURCE_FILE="$WORKSPACE/system/system/etc/floating_feature.xml"
    local TARGET_FILE="$STOCK_FW/system/system/etc/floating_feature.xml"

    local FEATURE TAG_NAME SOURCE_VALUE TARGET_VALUE
    local SOURCE_FEATURES TARGET_FEATURES

    # Dynamically extract all unique feature tags from both XML files
    SOURCE_FEATURES="$(grep -o 'SEC_FLOATING_FEATURE_[A-Za-z0-9_]*' "$SOURCE_FILE" | sort -u)"
    TARGET_FEATURES="$(grep -o 'SEC_FLOATING_FEATURE_[A-Za-z0-9_]*' "$TARGET_FILE" | sort -u)"

    # Step 1: Process existing Workspace features
    for FEATURE in $SOURCE_FEATURES; do
        TAG_NAME="${FEATURE#SEC_FLOATING_FEATURE_}"

        # Skip blacklisted features (keeps workspace value untouched)
        if grep -q -w -E "(${FEATURE}|${TAG_NAME})" <<< "$BLACKLIST"; then
            continue
        fi

        SOURCE_VALUE="$(GET_FF_VAL "extra" "$FEATURE")"
        TARGET_VALUE="$(GET_FF_VAL "stock" "$FEATURE")"

        # Check FALLBACK if feature is missing in stock firmware
        if [ -z "$TARGET_VALUE" ]; then
            TARGET_VALUE="$(grep -w -E "(${FEATURE}|${TAG_NAME})" <<< "$FALLBACK" | sed -n 's/^[^ ]* //p')"
        fi

        # Remove feature if absent everywhere; update if value changed
        if [ -z "$TARGET_VALUE" ]; then
            FF "$FEATURE" ""
        elif [ "$SOURCE_VALUE" != "$TARGET_VALUE" ]; then
            FF "$FEATURE" "$TARGET_VALUE"
        fi
    done

    # Step 2: Port missing Target Stock features
    for FEATURE in $TARGET_FEATURES; do
        TAG_NAME="${FEATURE#SEC_FLOATING_FEATURE_}"

        # Ignore blacklisted or deprecated features
        if grep -q -w -E "(${FEATURE}|${TAG_NAME})" <<< "$BLACKLIST" || \
           grep -q -w -E "(${FEATURE}|${TAG_NAME})" <<< "$DEPRECATED"; then
            continue
        fi

        # Add feature if completely missing from workspace
        if ! grep -q -w "$FEATURE" <<< "$SOURCE_FEATURES"; then
            FF "$FEATURE" "$(GET_FF_VAL "stock" "$FEATURE")"
        fi
    done
}
# ]

